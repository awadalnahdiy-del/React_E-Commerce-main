// نستورد أربع مكونات جاهزة من مجلد components:
// Navbar: شريط التنقل العلوي
// Main: القسم الرئيسي (غالبًا يحتوي بانر/سلايدر ترحيبي بالصفحة الرئيسية)
// Product: قسم عرض المنتجات (كروت المنتجات)
// Footer: تذييل الصفحة
// كذا نقدر نجمعهم كلهم بصفحة وحدة (Home) بدل ما نكتب كودهم من جديد
import { Navbar, Main, Product, Footer } from "../components";

// مكون فانكشن (Functional Component) اسمه Home
// وظيفته إنه يمثل الصفحة الرئيسية للموقع، وهو بس يجمع باقي المكونات ويرتبهم
// لاحظ إنه مكتوب بصيغة "function Home()" بدل "const Home = () =>"
// نفس الفكرة بس طريقة كتابة مختلفة (كلاهم صحيح بـ React)
function Home() {
  return (
    // نستخدم Fragment <>...</> عشان نرجع أكثر من عنصر بدون إضافة div زايد بالـ DOM
    <>
      {/* شريط التنقل يطلع فوق بكل الصفحات */}
      <Navbar />

      {/* القسم الرئيسي/الترحيبي بالصفحة (Hero Section) */}
      <Main />

      {/* قسم عرض المنتجات المتوفرة بالمتجر */}
      <Product />

      {/* تذييل الصفحة يطلع بالأسفل */}
      <Footer />
    </>
  )
}

// نصدّر المكون عشان نربطه بمسار "/" (الصفحة الرئيسية) بملف الراوتر App.js
export default Home